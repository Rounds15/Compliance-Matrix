import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
HOME = ROOT / "webpages" / "home"
SRC = HOME / "src"
DIST = HOME / "dist"

TOKEN = re.compile(r"\[\[metric:([a-z0-9_]+)\]\]")
UPDATED = re.compile(r"\[\[updated\]\]")

GENERATED = "GENERATED by tools/build_webpage.py - edit webpages/home/src/, not this file."

