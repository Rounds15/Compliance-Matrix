# ---------------------------------------------------------------------------
def load_metrics() -> dict:
    data = yaml.safe_load((HOME / "metrics.yaml").read_text(encoding="utf-8"))
    metrics = data.get("metrics") or {}
    if not metrics:
        raise SystemExit("metrics.yaml defines no metrics")
    for key, m in metrics.items():
        if "fallback" not in m:
            raise SystemExit(f"metric {key}: fallback is required")
        dv = m.get("dataverse")
        if not dv:
            raise SystemExit(f"metric {key}: a dataverse mapping is required")
        if dv.get("aggregate") not in ("count", "countdistinct"):
            raise SystemExit(f"metric {key}: aggregate must be count or countdistinct")
        if dv["aggregate"] == "countdistinct" and not dv.get("column"):
            raise SystemExit(f"metric {key}: countdistinct needs a column")
        sp = m.get("sharepoint")
        if sp and sp.get("aggregate") == "countdistinct" and not sp.get("field"):
            raise SystemExit(f"metric {key}: sharepoint countdistinct needs a field")
    return metrics


# ---------------------------------------------------------------------------
# Liquid web template
# ---------------------------------------------------------------------------
def fetchxml(key: str, m: dict) -> str:
    dv = m["dataverse"]
    distinct = dv["aggregate"] == "countdistinct"
    column = dv["column"] if distinct else dv["id"]
    agg = 'aggregate="countcolumn" distinct="true"' if distinct else 'aggregate="count"'

    conditions = []
    if dv.get("activeonly", True):
        conditions.append('<condition attribute="statecode" operator="eq" value="0" />')
    if dv.get("filter"):
        f = dv["filter"]
        conditions.append(
            f'<condition attribute="{f["column"]}" operator="eq" value="{f["value"]}" />'
        )

    lines = [
        '  <fetch aggregate="true">',
        f'    <entity name="{dv["entity"]}">',
        f'      <attribute name="{column}" alias="cm_value" {agg} />',
    ]
    if conditions:
        lines.append('      <filter type="and">')
        lines += [f"        {c}" for c in conditions]
        lines.append("      </filter>")
    lines += ["    </entity>", "  </fetch>"]
    return "\n".join(lines)


def build_webtemplate(source: str, metrics: dict) -> str:
    head = [
        "{% comment %}",
        f"  {GENERATED}",
        "",
        "  Compliance Matrix home page, server-rendered.",
        "",
        "  Each figure is a FetchXML aggregate run under the visitor's web role, so",
        "  the page needs no JavaScript and no Web API site settings. The tables",
        "  below need Read table permissions for whichever web role reaches this",
        "  page; without them the query returns nothing and the approved figure in",
        "  the markup is used instead, which is the intended degradation.",
        "",
        "  Tables read: " + ", ".join(sorted({m["dataverse"]["entity"] for m in metrics.values()})),
        "{% endcomment %}",
        "",
    ]

    for key, m in metrics.items():
        head += [
            f'{{% comment %}} {m.get("label", key)} {{% endcomment %}}',
            f"{{% fetchxml cm_{key}_q %}}",
            fetchxml(key, m),
            "{% endfetchxml %}",
            f"{{% assign cm_{key} = cm_{key}_q.results.entities[0].cm_value %}}",
            f"{{% if cm_{key} == blank %}}{{% assign cm_{key} = {m['fallback']} %}}{{% endif %}}",
            "",
        ]

    body = TOKEN.sub(lambda mo: "{{ cm_" + mo.group(1) + " }}", source)
    body = UPDATED.sub("Figures current as of {{ now | date: 'MMMM d, yyyy' }}", body)
    return "\n".join(head) + body


# ---------------------------------------------------------------------------
# Page copy + client-side script
# ---------------------------------------------------------------------------
def strip_source_comment(html: str) -> str:
    """Drop the authoring comment at the top of the source file."""
    return re.sub(r"\A<!--.*?-->\s*", "", html, flags=re.S)


def build_pagecopy(source: str, metrics: dict) -> str:
    def span(mo):
        key = mo.group(1)
        return (f'<span class="cm-metric" data-cm-metric="{key}">'
                f'{metrics[key]["fallback"]}</span>')

    body = TOKEN.sub(span, source)
    body = UPDATED.sub("&nbsp;", body)
    header = (
        "<!--\n"
        f"  {GENERATED}\n\n"
        "  Paste into the page's Copy field. Every figure carries the approved\n"
        "  number as its own text, so the page is correct before cm-metrics.js\n"
        "  runs and stays correct if the query is blocked.\n"
        "-->\n"
    )
    return header + body


def js_metric(key: str, m: dict) -> str:
    dv = m["dataverse"]
    distinct = dv["aggregate"] == "countdistinct"

    clauses = []
    if dv.get("activeonly", True):
        clauses.append("statecode eq 0")
    if dv.get("filter"):
        f = dv["filter"]
        clauses.append(f'{f["column"]} eq {f["value"]}')
    dv_filter = " and ".join(clauses)

    dv_js = (
        "{ set: %s, select: %s, distinct: %s, field: %s, filter: %s }"
        % (
            q(dv["set"]),
            q(dv["id"]),
            "true" if distinct else "false",
            q(dv.get("webapifield") or dv.get("column")) if distinct else "null",
            q(dv_filter) if dv_filter else "null",
        )
    )

    sp = m.get("sharepoint")
    if sp:
        sp_distinct = sp.get("aggregate") == "countdistinct"
        sp_filter = None
        if sp.get("filter"):
            f = sp["filter"]
            value = f["value"]
            value = value if isinstance(value, (int, float)) else "'%s'" % str(value).replace("'", "''")
            sp_filter = f'{f["field"]} eq {value}'
        sp_js = (
            "{ list: %s, distinct: %s, field: %s, filter: %s }"
            % (
                q(sp["list"]),
                "true" if sp_distinct else "false",
                q(sp.get("field")) if sp.get("field") else "null",
                q(sp_filter) if sp_filter else "null",
            )
        )
    else:
        sp_js = "null"

    return (
        f"  /* {m.get('label', key)} */\n"
        f"  {{\n"
        f"    key: {q(key)},\n"
        f"    fallback: {m['fallback']},\n"
        f"    dataverse: {dv_js},\n"
        f"    sharepoint: {sp_js}\n"
        f"  }}"
    )


def q(value) -> str:
    if value is None:
        return "null"
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_js(runtime: str, metrics: dict) -> str:
    head = [
        "/* " + GENERATED + " */",
        "/* ---------------------------------------------------------------------------",
        " * Compliance Matrix home page metrics",
        " * -------------------------------------------------------------------------",
        " * Paste this whole file into the page's JavaScript (Design Studio > the page",
        " * > ... > Edit code > JavaScript), or add it as a web file and reference it.",
        " *",
        " * Set backend below:",
        ' *   "dataverse"   Power Pages Web API. Needs the Webapi/* site settings and',
        " *                 Read table permissions - see dist/SETUP-VALUES.md.",
        ' *   "sharepoint"  SharePoint REST. Only works when this page is served from',
        " *                 the same SharePoint origin as the lists; a Power Pages site",
        " *                 is a different origin and the browser will block it.",
        ' *   "mock"        Renders the fallback figures. Used by preview.html.',
        " * ------------------------------------------------------------------------ */",
        "",
        "window.CM_CONFIG = {",
        '  backend: "dataverse",',
        "",
        "  // Only read when backend is \"sharepoint\". No trailing slash.",
        '  sharePointSite: "https://syr.sharepoint.com/sites/ComplianceMatrix",',
        "",
        "  // Counts are held in sessionStorage this long, so moving around the site",
        "  // does not re-run every query. 0 disables the cache.",
        "  cacheMinutes: 30,",
        "",
        "  // Page size when a count has to be taken by paging.",
        "  pageSize: 5000,",
        "",
        '  updatedPrefix: "Figures current as of ",',
        "",
        "  // true logs every request to the console.",
        "  debug: false",
        "};",
        "",
        "/* Query definitions, generated from webpages/home/metrics.yaml. */",
        "window.CM_METRICS = [",
        ",\n".join(js_metric(k, m) for k, m in metrics.items()),
        "];",
        "",
    ]
    return "\n".join(head) + "\n" + runtime


