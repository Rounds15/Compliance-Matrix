#!/usr/bin/env python3
"""
Build the Compliance Matrix home page from one design source and one metric
registry.

Inputs
    webpages/home/metrics.yaml          what each number on the page means
    webpages/home/src/home.source.html  the approved markup, with [[metric:k]]
    webpages/home/src/runtime.js        the client-side counter
    webpages/home/src/styles.css        optional supplemental CSS

Outputs (webpages/home/dist/, all generated - never edit them)
    home.webtemplate.html   Liquid web template. Counts run server-side through
                            fetchxml aggregates, so the page needs no JS and no
                            Web API configuration.
    home.pagecopy.html      Plain markup for the page-copy editor. Counts are
                            filled in by cm-metrics.js.
    cm-metrics.js           Generated query config + the runtime, one file to
                            paste into the page's JavaScript.
    cm-metrics.css          Copy of the supplemental CSS.
    preview.html            Standalone, opens in any browser, mock backend.
    SETUP-VALUES.md         The exact site settings and table permissions the
                            client-side path needs, derived from metrics.yaml.

Usage
    python3 tools/build_webpage.py            # write dist/
    python3 tools/build_webpage.py --check    # fail if dist/ is out of date
"""

from __future__ import annotations

