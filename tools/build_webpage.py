# Setup values
# ---------------------------------------------------------------------------
def build_setup(metrics: dict) -> str:
    tables: dict[str, set[str]] = {}
    for m in metrics.values():
        dv = m["dataverse"]
        fields = tables.setdefault(dv["entity"], set())
        fields.add(dv["id"])
        if dv["aggregate"] == "countdistinct":
            fields.add(dv["column"])
        if dv.get("activeonly", True):
            fields.add("statecode")
        if dv.get("filter"):
            fields.add(dv["filter"]["column"])

    lines = [
        f"<!-- {GENERATED} -->",
        "",
        "# Setup values",
        "",
        "Derived from `webpages/home/metrics.yaml`. Everything here is for the",
        "**client-side** path only (page copy + `cm-metrics.js` with the `dataverse`",
        "backend). The Liquid web template needs none of it - only the table",
        "permissions in the second section.",
        "",
        "## 1. Web API site settings",
        "",
        "Power Pages Design Studio, or the Portal Management app under **Site**",
        "**Settings**. Create these for the site that hosts the page.",
        "",
        "| Name | Value |",
        "|---|---|",
        "| `Webapi/error/innererror` | `true` (development only - remove before go-live) |",
    ]
    for table in sorted(tables):
        lines.append(f"| `Webapi/{table}/enable` | `true` |")
    for table, fields in sorted(tables.items()):
        lines.append(f"| `Webapi/{table}/fields` | `{','.join(sorted(fields))}` |")
    lines += [
        "",
        "`*` works in place of any field list and is easier to maintain, but it exposes",
        "every column on the table to the Web API for whoever holds the table",
        "permission. The lists above are the minimum these six figures need.",
        "",
        "A lookup is named by its logical name in the site setting and by",
        "`_<name>_value` in a `$select`; the generated script already uses the right",
        "form in each place.",
        "",
        "## 2. Table permissions",
        "",
        "One **Read** permission per table, **Global** scope, granted to the web role",
        "that reaches the page. Both paths need these - Liquid and the Web API are both",
        "filtered by them.",
        "",
        "| Table | Privilege | Scope |",
        "|---|---|---|",
    ]
    for table in sorted(tables):
        lines.append(f"| `{table}` | Read | Global |")
    lines += [
        "",
        "**Read this before granting the Anonymous Users role.** A Global Read",
        "permission is not scoped to counting - it lets that role read every row in",
        "the table through Liquid and, where the Web API is enabled, through",
        "`/_api/<table>`. Six aggregate figures on a public page are not worth",
        "publishing the obligation register to the internet. Either put the page",
        "behind authentication, or publish a snapshot instead (README, \"Public page",
        "without public data\").",
        "",
        f"Generated from {len(metrics)} metrics across {len(tables)} tables.",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
def build_all() -> dict[str, str]:
    metrics = load_metrics()
    source = strip_source_comment((SRC / "home.source.html").read_text(encoding="utf-8"))
    runtime = (SRC / "runtime.js").read_text(encoding="utf-8")
    styles = (SRC / "styles.css").read_text(encoding="utf-8")

    for key in TOKEN.findall(source):
        if key not in metrics:
            raise SystemExit(f"home.source.html uses [[metric:{key}]], "
                             f"which metrics.yaml does not define")
    used = set(TOKEN.findall(source))
    for key in metrics:
        if key not in used:
            raise SystemExit(f"metrics.yaml defines {key}, which the page never uses")

    pagecopy = build_pagecopy(source, metrics)
    return {
        "home.webtemplate.html": build_webtemplate(source, metrics),
        "home.pagecopy.html": pagecopy,
        "cm-metrics.js": build_js(runtime, metrics),
        "cm-metrics.css": f"/* {GENERATED} */\n" + styles,
        "preview.html": build_preview(pagecopy, metrics),
        "SETUP-VALUES.md": build_setup(metrics),
    }


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if dist/ differs from a fresh build")
    args = ap.parse_args(argv)

    files = build_all()

    if args.check:
        stale = []
        for name, text in files.items():
            path = DIST / name
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        if stale:
            print("dist/ is out of date: " + ", ".join(sorted(stale)))
            print("run: python3 tools/build_webpage.py")
            return 1
        print(f"dist/ is current ({len(files)} files)")
        return 0

    DIST.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (DIST / name).write_text(text, encoding="utf-8")
        print(f"  wrote webpages/home/dist/{name}")
    print(f"{len(files)} files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
